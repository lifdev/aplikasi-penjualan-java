        public void loadData(){
        model.getDataVector().removeAllElements();
        
        model.fireTableDataChanged();
        
        try {
            Connection cn = koneksi.getConnection();
            st = cn.createStatement();
            
            String sql = "SELECT * FROM barang";
            rs = st.executeQuery(sql);
            
            while (rs.next()) {
                Object[] o = new Object[7];
                o [0] = rs.getString("ID_Barang");
                o [1] = rs.getString("Nama_Barang");
                o [2] = rs.getString("Jenis");
                o [3] = rs.getString("Ukuran");
                o [4] = rs.getString("Harga_Beli");
                o [5] = rs.getString("Harga_Jual");
                o [6] = rs.getString("Stok");
                
                model.addRow(o);
            }
            rs.close();
            st.close();
        } catch (Exception e) {
            System.out.println("terjadi kesalahan");
        }
    }
        
    public void cariData(){
        DefaultTableModel tabel = new DefaultTableModel();
        
        tabel.addColumn("ID Barang");
        tabel.addColumn("Nama Barang");
        tabel.addColumn("Jenis");
        tabel.addColumn("Ukuran");
        tabel.addColumn("Harga_Beli");
        tabel.addColumn("Harga_Jual");
        tabel.addColumn("Stok");
        
        try {
            Connection cn = koneksi.getConnection();
            String sql = "Select * from barang where ID_Barang like '%" + jTextField1.getText() + "%'" +
                    "or Nama_Barang like '%" + jTextField1.getText() + "%'";
            st = cn.createStatement();
            rs = st.executeQuery(sql);
            while (rs.next()) {                
                tabel.addRow(new Object[]{
                    rs.getString(1),
                    rs.getString(2),
                    rs.getString(3),
                    rs.getString(4),
                    rs.getString(5),
                    rs.getString(6),
                    rs.getString(7),
                });
            }
            jTable1.setModel(tabel);
        } catch (Exception e) {
            System.out.println("Cari Data Error");
        }finally{
        }
    }
        
