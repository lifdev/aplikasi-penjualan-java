    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed
        // TODO add your handling code here:
        String id = txID.getText();
        String nama = txNama.getText();
        String jenis = (String) cbJenis.getSelectedItem();
        String ukuran = (String) cbUkuran.getSelectedItem();
        String hargaBeli = txHargaB.getText();
        String hargaJual = txHargaJ.getText();
        String stok = txStok.getText();

    if (id.isEmpty() || nama.isEmpty() || jenis == null || ukuran == null || 
        hargaBeli.isEmpty() || hargaJual.isEmpty() || stok.isEmpty()) {
        JOptionPane.showMessageDialog(null, "Semua data harus diisi dengan lengkap!");
        return;
    }

    try {
        Integer.parseInt(hargaBeli);
        Integer.parseInt(hargaJual);
        Integer.parseInt(stok);
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(null, "Harga Beli, Harga Jual, dan Stok harus berupa angka!");
        return;
    }

    try {
        Connection cn = koneksi.getConnection();
        if (cn == null) {
            JOptionPane.showMessageDialog(null, "Koneksi ke database gagal!");
            return;
        }

        String sql = "INSERT INTO BARANG VALUES (?, ?, ?, ?, ?, ?, ?)";
        PreparedStatement p = cn.prepareStatement(sql);
        p.setString(1, id);
        p.setString(2, nama);
        p.setString(3, jenis);
        p.setString(4, ukuran);
        p.setString(5, hargaBeli);
        p.setString(6, hargaJual);
        p.setString(7, stok);

        System.out.println("SQL Query: " + sql);
        System.out.println("ID: " + id);
        System.out.println("Nama: " + nama);
        System.out.println("Jenis: " + jenis);
        System.out.println("Ukuran: " + ukuran);
        System.out.println("Harga Beli: " + hargaBeli);
        System.out.println("Harga Jual: " + hargaJual);
        System.out.println("Stok: " + stok);

        p.executeUpdate();
        p.close();

        JOptionPane.showMessageDialog(null, "Data Tersimpan");
        loadData();
        clear();
    
    } catch (Exception e) {
        JOptionPane.showMessageDialog(null, "Kesalahan: " + e.getMessage());
        e.printStackTrace();
    }
    }//GEN-LAST:event_btnSimpanActionPerformed

    private void btnEditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditActionPerformed
        // TODO add your handling code here:
        int i = jTable1.getSelectedRow();
        if (i == -1) {
            return;
        }
        String id = (String) model.getValueAt(i, 0);
        String nama = txNama.getText();
        String jenis = (String)cbJenis.getSelectedItem();
        String ukuran = (String)cbUkuran.getSelectedItem();
        String hargaBeli = txHargaB.getText();
        String hargaJual = txHargaJ.getText();
        String stok = txStok.getText();
        
        try {
            Connection cn = koneksi.getConnection();
            String sql = "UPDATE barang SET Nama_Barang = ?, Jenis = ?, Ukuran = ?, Harga_Beli = ?, Harga_Jual = ?, Stok = ? WHERE ID_Barang = ?";
            PreparedStatement p = cn.prepareStatement(sql);
            p.setString(1, nama);
            p.setString(2, jenis);
            p.setString(3, ukuran);
            p.setString(4, hargaBeli);
            p.setString(5, hargaJual);
            p.setString(6, stok);
            p.setString(7, id);
            
            p.executeUpdate();
            p.close();
            JOptionPane.showMessageDialog(null, "Data Terubah");
            btnSimpan.setEnabled(true);
            btnEdit.setEnabled(false);
            btnHapus.setEnabled(false);
            btnBatal.setEnabled(false);
            clear();
        } catch (Exception e) {
            System.out.println("update error");
        }finally{
            loadData();
        }
    }//GEN-LAST:event_btnEditActionPerformed

    private void btnHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHapusActionPerformed
        // TODO add your handling code here:
        int i = jTable1.getSelectedRow();
        if (i == -1) {
            return;
        }
        
        String id = (String) model.getValueAt(i, 0);
        
        int pernyataan = JOptionPane.showConfirmDialog(null, "Yakin Data Akan Dihapus","Konfirmasi", JOptionPane.OK_CANCEL_OPTION, JOptionPane.QUESTION_MESSAGE);
        if (pernyataan== JOptionPane.OK_OPTION) {
            try {
                Connection cn = koneksi.getConnection();
                String sql = "DELETE FROM barang WHERE ID_Barang = ?";
                PreparedStatement p = cn.prepareStatement(sql);
                p.setString(1, id);
                p.executeUpdate();
                p.close();
                JOptionPane.showMessageDialog(null, "Data Terhapus");
            } catch (Exception e) {
                System.out.println("Terjadi Kesalahan");
            }finally{
                btnSimpan.setEnabled(true);
                btnEdit.setEnabled(false);
                btnHapus.setEnabled(false);
                btnBatal.setEnabled(false);
                loadData();
                clear();
            }
        }
        if (pernyataan== JOptionPane.CANCEL_OPTION) {
            
        }
    }//GEN-LAST:event_btnHapusActionPerformed

